// Builds src/params/fxPresets.generated.ts: the FX presets the synth offers on knob 2 of the
// Pre-/Post-FX pages (Chorus 1, Warm, Drive 2, ...), from Edisyn's Hydrasynth driver, which
// lists their names (FX_PRESETS) and the NRPN values they set (FX_PRESET_VALUES). A preset isn't
// stored in the patch: picking one sets the type's five params.
// Usage: npx vite-node tools/generateFxPresets.ts [path to ASMHydrasynth.java]
import { readFileSync, writeFileSync } from 'node:fs'
import { param } from '../src/params/patch'

const file = process.argv[2] ?? 'local/edisyn/edisyn/synth/asmhydrasynth/ASMHydrasynth.java'
const src = readFileSync(file, 'utf8')
const commit = readFileSync('local/extract/EDISYN_COMMIT', 'utf8').trim()

/** The text between the braces that open after `marker`. */
function braced(marker: string): string {
  const start = src.indexOf('{', src.indexOf(marker))
  let depth = 0
  for (let i = start; i < src.length; i++) {
    if (src[i] === '{') depth++
    else if (src[i] === '}' && --depth === 0) return src.slice(start + 1, i)
  }
  throw new Error(`${marker}: unbalanced`)
}

/** Top-level `{ ... }` groups of a braced list. */
function groups(text: string): string[] {
  const out: string[] = []
  let depth = 0
  let start = -1
  for (let i = 0; i < text.length; i++) {
    if (text[i] === '{' && depth++ === 0) start = i + 1
    else if (text[i] === '}' && --depth === 0) out.push(text.slice(start, i))
  }
  return out
}

const names = groups(braced('String[][] FX_PRESETS =')).map((g) => [...g.matchAll(/"([^"]*)"/g)].map((m) => m[1]))
const values = groups(braced('int[][][] FX_PRESET_VALUES =')).map((type) =>
  groups(type).map((preset) =>
    preset
      .replace(/\/\/.*$/gm, '')
      .split(',')
      .map((v) => v.trim())
      .filter(Boolean)
      .map((v) => {
        const m = /^0x([0-9a-f]+)\s*\*\s*128\s*\+\s*0x([0-9a-f]+)$/i.exec(v)
        if (!m) throw new Error(`unexpected value ${v}`)
        return parseInt(m[1], 16) * 128 + parseInt(m[2], 16)
      }),
  ),
)
if (names.length !== values.length) throw new Error(`${names.length} name lists, ${values.length} value lists`)

// Per type: each preset's name and its five params' values (NRPN value back to the param's).
const presets = names.map((list, type) => {
  if (list.length !== values[type].length) throw new Error(`type ${type}: ${list.length} names, ${values[type].length} value sets`)
  return list.map((name, i) => {
    const row = values[type][i]
    if (row[0] !== type * 8 || row[1] !== i * 8) throw new Error(`type ${type} preset ${i}: header ${row[0]}, ${row[1]}`)
    const params = row.slice(2, 7).map((nrpn, j) => {
      const def = param(`prefx${type}param${j + 1}`)
      const spec = def.nrpn
      if (!spec || 'table' in spec) throw new Error(`${def.key}: no linear NRPN`)
      // Rotary 2's Hi-Depth is listed as 233, off the step of 8 (a typo for 232, most likely):
      // rounded, and reported.
      const exact = (nrpn - spec.base) / spec.mul
      const v = Math.round(exact)
      if (v !== exact) console.warn(`${name} ${def.key}: NRPN ${nrpn} is ${exact}, rounded to ${v}`)
      if (v < def.min || v > def.max) throw new Error(`${name} ${def.key}: ${nrpn} -> ${v}, outside ${def.min}..${def.max}`)
      return v
    })
    return { name, params }
  })
})

const out = `// GENERATED by tools/generateFxPresets.ts -- do not edit.
// From Edisyn's ASM Hydrasynth driver (https://github.com/eclab/edisyn, commit ${commit}),
// Copyright 2023 Sean Luke, Apache License 2.0; see NOTICE.
// The FX presets per FX type (index = prefxtype/postfxtype value): each one's name and the values
// it sets on the type's five params (param1..param5). Not stored in the patch.
export interface FxPreset {
  name: string
  params: number[]
}

export const FX_PRESETS: FxPreset[][] = [
${presets.map((list) => `  [${list.map((p) => JSON.stringify(p)).join(', ')}],`).join('\n')}
]
`
writeFileSync('src/params/fxPresets.generated.ts', out)
