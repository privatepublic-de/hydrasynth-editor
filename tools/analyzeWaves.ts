// Reads the 219 wave pictures (public/waves, Thierry Rochebois Zic, CC BY 4.0) and writes what
// they show as numbers to src/ui/waveFeatures.generated.ts: the 24 harmonic bars' levels, the
// hue the picture's author gave the wave's group, and how jagged the drawn cycle is.
// Usage: npx vite-node tools/analyzeWaves.ts
import { readFileSync, writeFileSync } from 'node:fs'
import { PNG } from 'pngjs'
import { choicesOf } from '../src/params/display'
import { param } from '../src/params/patch'

const WAVES = 219
// The bar strip: 24 slots 8 px apart from x = 18, lit from y = 8 to 20 (measured on the images).
const BAR_X0 = 18
const BAR_STEP = 8
const BAR_Y = 14
// The drawn cycle lies below the bars; the name (white, unsaturated) sits bottom left.
const TRACE_Y0 = 24
const TRACE_Y1 = 100
const TRACE_X0 = 8
const TRACE_X1 = 212

function rgbAt(img: PNG, x: number, y: number): [number, number, number] {
  const i = (y * img.width + x) * 4
  return [img.data[i], img.data[i + 1], img.data[i + 2]]
}

function hsl([r, g, b]: [number, number, number]) {
  const max = Math.max(r, g, b) / 255
  const min = Math.min(r, g, b) / 255
  const l = (max + min) / 2
  const d = max - min
  const s = d === 0 ? 0 : d / (1 - Math.abs(2 * l - 1))
  let h = 0
  if (d) {
    const [R, G, B] = [r / 255, g / 255, b / 255]
    h = max === R ? ((G - B) / d) % 6 : max === G ? (B - R) / d + 2 : (R - G) / d + 4
    h = (h * 60 + 360) % 360
  }
  return { h, s, l }
}

const names = choicesOf(param('osc1wavscanwave1')).map(([, n]) => n)
const out: { name: string; harmonics: number[]; hue: number; jagged: number }[] = []
for (let w = 0; w < WAVES; w++) {
  const img = PNG.sync.read(readFileSync(`public/waves/${w}.png`))
  const bars = Array.from({ length: 24 }, (_, k) => {
    let best = 0
    for (let dx = 0; dx < 3; dx++) {
      const [r, g, b] = rgbAt(img, BAR_X0 + BAR_STEP * k + dx, BAR_Y)
      best = Math.max(best, Math.max(r, g, b))
    }
    return best
  })
  const peak = Math.max(...bars, 1)
  const harmonics = bars.map((b) => Math.round((b / peak) * 1000) / 1000)

  // Hue of the brightest bar: the group colour.
  const loudest = bars.indexOf(peak)
  let hue = 0
  for (let dx = 0; dx < 3; dx++) {
    const c = hsl(rgbAt(img, BAR_X0 + BAR_STEP * loudest + dx, BAR_Y))
    if (c.s > 0.2) hue = Math.round(c.h)
  }

  // The trace: per column the mean y of saturated pixels; jaggedness = mean |dy| between columns.
  const ys: number[] = []
  for (let x = TRACE_X0; x <= TRACE_X1; x++) {
    let sum = 0
    let n = 0
    for (let y = TRACE_Y0; y < TRACE_Y1; y++) {
      const c = hsl(rgbAt(img, x, y))
      if (c.s > 0.25 && c.l > 0.2) {
        sum += y
        n++
      }
    }
    if (n) ys.push(sum / n)
  }
  let travel = 0
  for (let i = 1; i < ys.length; i++) travel += Math.abs(ys[i] - ys[i - 1])
  const jagged = ys.length > 1 ? Math.round((travel / (ys.length - 1)) * 1000) / 1000 : 0

  out.push({ name: names[w], harmonics, hue, jagged })
}

const src = `// GENERATED by tools/analyzeWaves.ts from public/waves (Thierry Rochebois Zic, CC BY 4.0) -- do not edit.
// Per wave (0..218): its name, the 24 harmonic bars as 0..1 of the loudest (the pictures'
// brightness, roughly a level scale), the hue of its group's colour, and the mean slope of its
// drawn cycle in pixels per column (smooth waves low, noisy ones high).
export interface WaveFeatures {
  name: string
  harmonics: number[]
  hue: number
  jagged: number
}

export const WAVE_FEATURES: WaveFeatures[] = [
${out.map((w) => `  ${JSON.stringify(w)},`).join('\n')}
]
`
writeFileSync('src/ui/waveFeatures.generated.ts', src)
const hues = new Map<number, string[]>()
for (const w of out) hues.set(Math.round(w.hue / 20) * 20, [...(hues.get(Math.round(w.hue / 20) * 20) ?? []), w.name])
for (const [h, ns] of [...hues].sort((a, b) => a[0] - b[0])) console.log(String(h).padStart(3), ns.length, ns.slice(0, 12).join(', '))
